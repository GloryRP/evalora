/**
 * bulkCreateStudents - Creates multiple students from parsed Excel/CSV data
 * POST /api/v1/admin/students/bulk
 * Body: { records: [{ usn, name, department, semester, email, phone, password }] } or { students: [...] }
 */
const bulkCreateStudents = async (req, res) => {
  const records = req.body.records || req.body.students || req.body.data;
  if (!Array.isArray(records) || records.length === 0) {
    return res.status(400).json({ success: false, message: 'No records provided' });
  }

  let created = 0, skipped = 0;
  const errors = [];

  for (let i = 0; i < records.length; i++) {
    const record = records[i];
    const rowNum = i + 1;
    try {
      const { usn, name, department, semester, email, phone, batch } = record;
      if (!usn || !name || !department || semester === undefined || semester === null || semester === '') {
        errors.push({ row: rowNum, rowNumber: rowNum, usn: usn || '?', reason: 'Missing required fields (usn, name, department, semester)' });
        skipped++;
        continue;
      }

      const cleanUsn = usn.toString().trim().toUpperCase();

      // F10: Validate USN format (e.g. 1PE21CS001, 4PM23CD099)
      const isValidUsn = /^[a-zA-Z0-9]{3}\d{2}[a-zA-Z]{2}\d{3}$/i.test(cleanUsn);
      if (!isValidUsn) {
        errors.push({ row: rowNum, rowNumber: rowNum, usn: cleanUsn, reason: `Malformed USN "${cleanUsn}" (expected standard format like 4PM23CD001)` });
        skipped++;
        continue;
      }

      const semNum = parseInt(semester);
      if (isNaN(semNum) || semNum < 1 || semNum > 8) {
        errors.push({ row: rowNum, rowNumber: rowNum, usn: cleanUsn, reason: `Invalid semester "${semester}" (must be between 1 and 8)` });
        skipped++;
        continue;
      }

      const deptDoc = await resolveDepartment(department);
      if (!deptDoc) {
        errors.push({ row: rowNum, rowNumber: rowNum, usn: cleanUsn, reason: `Unknown department "${department}".` });
        skipped++;
        continue;
      }
      const canonicalDept = deptDoc.departmentName;

      const existing = await User.findOne({ username: cleanUsn });
      if (existing) {
        skipped++;
        errors.push({ row: rowNum, rowNumber: rowNum, usn: cleanUsn, reason: 'Already exists' });
        continue;
      }
      
      // Auto-generate password: USN@123
      const autoGeneratedPassword = `${cleanUsn}@123`;
      const passwordHash = await bcrypt.hash(autoGeneratedPassword, 10);
      
      await User.create({ username: cleanUsn, passwordHash, role: 'student', name, department: canonicalDept, email, isFirstLogin: true });
      await Student.create({
        usn: cleanUsn,
        name,
        department: canonicalDept,
        semester: semNum,
        email,
        phone,
        batch: batch || deriveBatchFromUsn(cleanUsn),
      });
      created++;
    } catch (err) {
      skipped++;
      errors.push({ row: rowNum, rowNumber: rowNum, usn: record.usn || '?', reason: err.code === 11000 ? 'Already exists' : err.message });
    }
  }
  res.json({ success: true, data: { created, skipped, errors }, summary: { created, skipped, total: records.length, errors } });
};

