/**
 * createStudent - Creates a new student and their User account
 * POST /api/v1/admin/students
 * Body: { usn, name, department, semester, email, phone, password, batch }
 */
const createStudent = async (req, res) => {
  try {
    const { usn, name, department, semester, email, phone, batch } = req.body;

    // Resolve & normalise department to canonical name
    const deptDoc = await resolveDepartment(department);
    if (!deptDoc) {
      return res.status(400).json({
        success: false,
        message: `Department "${department}" not found. Please select a valid department from the list.`,
      });
    }
    const canonicalDept = deptDoc.departmentName;

    // Check if user with this USN already exists
    const existingUser = await User.findOne({ username: usn.toUpperCase() });
    if (existingUser) {
      return res.status(400).json({
        success: false,
        message: 'A user with this USN already exists.',
      });
    }

    // Auto-generate password: USN@123
    const autoGeneratedPassword = `${usn.toUpperCase()}@123`;
    const passwordHash = await bcrypt.hash(autoGeneratedPassword, 10);

    // Create User record for authentication
    await User.create({
      username: usn.toUpperCase(),
      passwordHash,
      role: 'student',
      name,
      department: canonicalDept,
      email,
      isFirstLogin: true,
    });

    // Create Student profile record
    const student = await Student.create({
      usn: usn.toUpperCase(),
      name,
      department: canonicalDept,
      semester,
      email,
      phone,
      batch: batch || deriveBatchFromUsn(usn),
    });

    res.status(201).json({
      success: true,
      message: 'Student created successfully.',
      data: student,
    });
  } catch (error) {
    console.error('Create student error:', error);

    if (error.code === 11000) {
      return res.status(400).json({
        success: false,
        message: 'A student with this USN already exists.',
      });
    }

    res.status(500).json({
      success: false,
      message: 'An error occurred while creating the student.',
      error: error.message,
    });
  }
};

