/**
 * createFaculty - Creates a new faculty member and their User account
 * POST /api/v1/admin/faculty
 */
const createFaculty = async (req, res) => {
  let createdUser = null;

  try {
    const { employeeId, name, department, designation, subjectsAssigned, email, phone } = req.body;

    // Resolve & normalise department to canonical name
    const deptDoc = await resolveDepartment(department);
    if (!deptDoc) {
      return res.status(400).json({
        success: false,
        message: `Department "${department}" not found. Please select a valid department from the list.`,
      });
    }
    const canonicalDept = deptDoc.departmentName;

    const cleanEmpId = employeeId ? employeeId.toString().trim().toUpperCase() : '';
    if (!cleanEmpId) {
      return res.status(400).json({
        success: false,
        message: 'Employee ID is required.',
      });
    }

    // Check if user or faculty with this Employee ID already exists
    const existingUser = await User.findOne({ username: cleanEmpId });
    if (existingUser) {
      return res.status(400).json({
        success: false,
        message: 'A user with this Employee ID already exists.',
        field: 'employeeId',
      });
    }

    const existingFaculty = await Faculty.findOne({ employeeId: cleanEmpId });
    if (existingFaculty) {
      return res.status(400).json({
        success: false,
        message: 'A faculty member with this Employee ID already exists.',
        field: 'employeeId',
      });
    }

    // Check if user or faculty with this Email already exists
    const cleanEmail = email && typeof email === 'string' && email.trim() ? email.trim().toLowerCase() : undefined;
    if (cleanEmail) {
      const existingEmailUser = await User.findOne({ email: cleanEmail });
      const existingEmailFaculty = await Faculty.findOne({ email: cleanEmail });
      if (existingEmailUser || existingEmailFaculty) {
        return res.status(400).json({
          success: false,
          message: 'A user with this Email already exists.',
          field: 'email',
        });
      }
    }

    const cleanPhone = phone && typeof phone === 'string' && phone.trim() ? phone.trim() : undefined;

    // Auto-generate password: EmployeeID@123
    const autoGeneratedPassword = `${cleanEmpId}@123`;
    const passwordHash = await bcrypt.hash(autoGeneratedPassword, 10);

    const isHodDesignation = designation && (
      designation.toLowerCase().includes('hod') ||
      designation.toLowerCase().includes('head of department')
    );
    const assignedRole = isHodDesignation ? 'hod' : 'faculty';

    const userPayload = {
      username: cleanEmpId,
      passwordHash,
      role: assignedRole,
      name,
      department: canonicalDept,
      email: cleanEmail,
      phone: cleanPhone,
      isFirstLogin: true,
    };

    const facultyPayload = {
      employeeId: cleanEmpId,
      name,
      department: canonicalDept,
      designation,
      subjectsAssigned: subjectsAssigned || [],
      email: cleanEmail,
      phone: cleanPhone,
    };

    // Create User record first
    createdUser = await User.create(userPayload);

    // Create Faculty profile record
    const faculty = await Faculty.create(facultyPayload);

    res.status(201).json({
      success: true,
      message: 'Faculty created successfully.',
      data: faculty,
    });
  } catch (error) {
    console.error('Create faculty error:', error);

    // Manual rollback if non-transactional user was created
    if (createdUser && createdUser._id) {
      try {
        await User.findByIdAndDelete(createdUser._id);
        console.log(`Rolled back orphan user ${createdUser.username} (${createdUser._id})`);
      } catch (cleanupErr) {
        console.error('Failed to cleanup orphan user:', cleanupErr);
      }
    }

    if (error.code === 11000) {
      const field = error.keyPattern
        ? Object.keys(error.keyPattern)[0]
        : (error.keyValue ? Object.keys(error.keyValue)[0] : 'field');
      const fieldDisplayMap = {
        username: 'Employee ID',
        employeeId: 'Employee ID',
        email: 'Email',
        phone: 'Phone number',
      };
      const fieldName = fieldDisplayMap[field] || field;
      return res.status(400).json({
        success: false,
        message: `A user or faculty with this ${fieldName} already exists.`,
        field,
      });
    }

    if (error.name === 'ValidationError') {
      return res.status(400).json({
        success: false,
        message: error.message,
      });
    }

    res.status(500).json({
      success: false,
      message: 'An error occurred while creating the faculty member.',
      error: error.message,
    });
  }
};

